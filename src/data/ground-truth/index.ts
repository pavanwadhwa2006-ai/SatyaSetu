// 9. REPRODUCIBLE BENCHMARK INTEGRITY VALIDATOR
// ============================================================

export interface ValidationReport {
  isValid: boolean;
  totalTenders: number;
  totalBidders: number;
  totalRequirements: number;
  totalDocuments: number;
  totalEvidence: number;
  totalComplianceResults: number;
  bidderValidation: {
    bidderCode: string;
    legalName: string;
    expectedBenchmark: string;
    actualBenchmark: string;
    passed: boolean;
    failingCount: number;
    reviewCount: number;
    passingCount: number;
  }[];
  integrityChecks: {
    name: string;
    passed: boolean;
    message: string;
  }[];
}

export const validateGroundTruthBenchmarks = (): ValidationReport => {
  const integrityChecks: { name: string; passed: boolean; message: string }[] = [];

  // Check 1: Exactly 3 tenders exist
  integrityChecks.push({
    name: '3 Tenders Configured',
    passed: groundTruthTenders.length === 3,
    message: `Found ${groundTruthTenders.length} tenders (Expected 3)`,
  });

  // Check 2: Exactly 5 bidders exist
  integrityChecks.push({
    name: '5 Bidders Configured',
    passed: groundTruthBidders.length === 5,
    message: `Found ${groundTruthBidders.length} bidders (Expected 5)`,
  });

  // Check 3: Apex is normalized to T3-B1
  const apexBidder = groundTruthBidders.find((b) => b.legalName.includes('Apex Electrical'));
  integrityChecks.push({
    name: 'Apex Normalized to T3-B1',
    passed: apexBidder?.bidderCode === 'T3-B1' && apexBidder?.tenderId === 'tender-t3',
    message: `Apex bidderCode is '${apexBidder?.bidderCode}' under tender '${apexBidder?.tenderId}'`,
  });

  // Check 4: All evidence records point to valid documents and bidders
  const orphanEvidence = bidderEvidence.filter(
    (e) =>
      !groundTruthBidders.some((b) => b.id === e.bidderId) ||
      !bidderDocuments.some((d) => d.id === e.documentId)
  );
  integrityChecks.push({
    name: 'Zero Orphan Evidence Records',
    passed: orphanEvidence.length === 0,
    message: orphanEvidence.length === 0 ? 'All evidence correctly linked to bidders & documents' : `Found ${orphanEvidence.length} orphan evidence items`,
  });

  // Check 5: Compliance results point to valid requirements
  const orphanCompliance = groundTruthComplianceResults.filter(
    (c) => !tenderRequirements.some((r) => r.id === c.requirementId)
  );
  integrityChecks.push({
    name: 'Zero Orphan Compliance Items',
    passed: orphanCompliance.length === 0,
    message: orphanCompliance.length === 0 ? 'All compliance items linked to requirements' : `Found ${orphanCompliance.length} orphan compliance items`,
  });

  // Bidder-specific benchmarks validation
  const expectedBenchmarksMap: Record<string, string> = {
    'T1-B2': 'NON_COMPLIANT',
    'T2-B1': 'COMPLIANT',
    'T2-B2': 'REVIEW',
    'T3-B1': 'COMPLIANT',
    'T3-B2': 'NON_COMPLIANT',
  };

  const bidderValidation = groundTruthBidders.map((b) => {
    const benchmark = bidderBenchmarks.find((bm) => bm.bidderId === b.id);
    const results = groundTruthComplianceResults.filter((c) => c.bidderId === b.id);
    const expected = expectedBenchmarksMap[b.bidderCode];
    const actual = benchmark?.benchmarkStatus || 'UNKNOWN';
    const passed = expected === actual;

    return {
      bidderCode: b.bidderCode,
      legalName: b.legalName,
      expectedBenchmark: expected,
      actualBenchmark: actual,
      passed,
      failingCount: results.filter((r) => r.status === 'FAIL').length,
      reviewCount: results.filter((r) => r.status === 'REVIEW').length,
      passingCount: results.filter((r) => r.status === 'PASS').length,
    };
  });

  const allBiddersPassed = bidderValidation.every((bv) => bv.passed);
  const allIntegrityPassed = integrityChecks.every((ic) => ic.passed);

  return {
    isValid: allBiddersPassed && allIntegrityPassed,
    totalTenders: groundTruthTenders.length,
    totalBidders: groundTruthBidders.length,
    totalRequirements: tenderRequirements.length,
    totalDocuments: bidderDocuments.length,
    totalEvidence: bidderEvidence.length,
    totalComplianceResults: groundTruthComplianceResults.length,
    bidderValidation,
    integrityChecks,
  };
};
